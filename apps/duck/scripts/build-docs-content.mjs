// Drop-in replacement for the old `velite` CLI step in `build:docs`.
// Reads the existing velite.config.ts (which uses
// `@gentleduck/md`'s `defineConfig`/`s` API under the hood), runs
// `build()` from `@gentleduck/md`, and then writes a velite-compatible
// `.gentleduck/index.js` + `index.d.ts` so all existing
// `import { ... } from '.gentleduck'` call-sites keep working unchanged.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { register } from 'node:module'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from '@gentleduck/md'

// Allow the script to load the .ts config without a separate tsx wrapper.
try {
  register('tsx/esm', pathToFileURL(join(process.cwd(), 'package.json')))
} catch {}

const root = process.cwd()
const configPath = resolve(root, 'duck-md.config.ts')
const mod = await import(pathToFileURL(configPath).href)
const config = mod.default ?? mod

const outDir = resolve(root, config.output?.data ?? '.gentleduck')

console.log(`[duck-md] building -> ${outDir}`)
console.log('[duck-md] config keys:', Object.keys(config))
console.log('[duck-md] collections:', Object.keys(config.collections ?? {}))
const report = await build(config)

// ANSI colors. Disabled when stdout is not a TTY (CI pipes, log
// captures) or when NO_COLOR is set so the output stays readable
// in plain-text consumers. Mirrors `clicolors`/`supports-color`.
const COLOR = !process.env.NO_COLOR && process.stdout.isTTY
const ansi = (n) => (s) => (COLOR ? `\x1b[${n}m${s}\x1b[0m` : s)
const red = ansi('31;1')
const yellow = ansi('33;1')
const blue = ansi('34;1')
const cyan = ansi('36;1')
const dim = ansi('2')
const bold = ansi('1')

const SEVERITY_PAINT = {
  bug: red,
  error: red,
  warning: yellow,
  help: cyan,
  note: blue,
}

function formatDiagnostic(d) {
  const paint = SEVERITY_PAINT[d.severity] ?? dim
  const head = `${paint(d.severity)}${dim('[')}${bold(d.code)}${dim(']')}: ${d.message}`
  const lines = [head]
  if (d.file) {
    const loc = d.line ? `${d.file}:${d.line}${d.column ? `:${d.column}` : ''}` : d.file
    lines.push(`  ${dim('-->')} ${loc}`)
  }
  if (d.help) lines.push(`  ${cyan('=')} ${bold('help')}: ${d.help}`)
  return lines.join('\n')
}

// Print one-by-one — flush each diagnostic before the next so a
// bombing build still surfaces the earliest signal even if the
// process gets killed midway.
const diagnostics = report?.diagnostics ?? []
if (diagnostics.length) {
  console.log(`[duck-md] ${diagnostics.length} diagnostic${diagnostics.length === 1 ? '' : 's'}:`)
  for (const d of diagnostics) {
    const stream = d.severity === 'error' || d.severity === 'bug' ? process.stderr : process.stdout
    stream.write(formatDiagnostic(d) + '\n')
  }
}

if (report?.errors?.length) {
  for (const e of report.errors) console.error(`  ${red('!')} ${e.file}: ${e.message}`)
  process.exit(1)
}

const collections = report?.collections ?? []
if (!collections.length) {
  console.log('[duck-md] nothing to write (no collections)')
  process.exit(0)
}

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })

// Map config keys (lowercase, used in TS imports) to the engine's
// collection name (which is what gets written to `<name>.json`).
// `name` defaults to the key when not set.
const cfgCollections = config.collections ?? {}
const entries = Object.entries(cfgCollections)
  .map(([key, c]) => ({ key, name: c?.name ?? key }))
  .sort((a, b) => a.key.localeCompare(b.key))

const indexJs =
  '// Generated by scripts/build-docs-content.mjs\n' +
  entries.map((e) => `export { default as ${e.key} } from './${e.name}.json' with { type: 'json' }`).join('\n') +
  '\n'

const indexDts =
  '// Generated by scripts/build-docs-content.mjs\n' +
  "import type __vc from '../duck-md.config'\n\n" +
  "type Collections = (typeof __vc)['collections']\n\n" +
  entries
    .map((e) => {
      const Cap = e.key.charAt(0).toUpperCase() + e.key.slice(1)
      return (
        `export type ${Cap} = NonNullable<Collections['${e.key}']['schema']>['_output']\n` +
        `export declare const ${e.key}: ${Cap}[]\n`
      )
    })
    .join('\n') +
  '\n'

writeFileSync(join(outDir, 'index.js'), indexJs)
writeFileSync(join(outDir, 'index.d.ts'), indexDts)

for (const c of collections) {
  console.log(`  ${c.name}: ${c.records} records -> ${c.outputPath}`)
}
console.log(`[duck-md] wrote ${entries.length} collection index entries`)
