/**
 * BCP-47 locale tag — language code optionally followed by a country code.
 *
 * @example
 * const fr: LocaleTag = 'fr-FR'
 * const en: LocaleTag = 'en'
 */
export type LocaleTag = LanguageCode | `${LanguageCode}-${CountryCode}`

