describe('adapter headers', () => {
  test('nextjs header includes @ts-nocheck directive', () => {
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('@ts-nocheck')
  })

  test('nextjs header includes autogenerated notice', () => {
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('autogenerated by @gentleduck/registry-build')
  })

  test('nextjs header imports React', () => {
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('import * as React from "react"')
  })

  test('nextjs header includes next/dynamic fallback', () => {
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('next/dynamic.js')
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('try {')
    expect(NEXTJS_COMPONENT_INDEX_HEADER).toContain('catch')
  })

  test('vite header includes @ts-nocheck directive', () => {
    expect(VITE_COMPONENT_INDEX_HEADER).toContain('@ts-nocheck')
  })

  test('vite header includes autogenerated notice', () => {
    expect(VITE_COMPONENT_INDEX_HEADER).toContain('autogenerated by @gentleduck/registry-build')
  })

  test('vite header imports React', () => {
    expect(VITE_COMPONENT_INDEX_HEADER).toContain('import * as React from "react"')
  })

  test('vite header does NOT reference next/dynamic', () => {
    expect(VITE_COMPONENT_INDEX_HEADER).not.toContain('dynamic')
    expect(VITE_COMPONENT_INDEX_HEADER).not.toContain('next/')
  })

  test('custom adapter defaultHeader is empty', () => {
    const adapter = getComponentIndexAdapter('custom')
    expect(adapter.defaultHeader).toBe('')
  })

  test('nextjs adapter defaultHeader matches NEXTJS_COMPONENT_INDEX_HEADER', () => {
    const adapter = getComponentIndexAdapter('nextjs')
    expect(adapter.defaultHeader).toBe(NEXTJS_COMPONENT_INDEX_HEADER)
  })

  test('vite adapter defaultHeader matches VITE_COMPONENT_INDEX_HEADER', () => {
    const adapter = getComponentIndexAdapter('vite')
    expect(adapter.defaultHeader).toBe(VITE_COMPONENT_INDEX_HEADER)
  })
})

