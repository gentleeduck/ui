describe('createComponentIndexEntry with rich items', () => {
  test('handles item with all optional fields populated', () => {
    const richItem = {
      name: 'combobox',
      type: 'registry:ui' as const,
      root_folder: 'components/ui',
      description: 'An autocomplete combobox component',
      source: 'https://github.com/example/combobox',
      categories: ['forms', 'inputs', 'autocomplete'],
      registryDependencies: ['popover', 'command', 'badge'],
      files: [{ path: 'components/ui/combobox.tsx', type: 'registry:ui' as const }],
      dependencies: ['cmdk'],
      devDependencies: ['@types/cmdk'],
    }

    const result = createComponentIndexEntry({ id: '_Combobox', item: richItem })

    expect(result).toContain('"combobox"')
    expect(result).toContain('An autocomplete combobox component')
    expect(result).toContain('https://github.com/example/combobox')
    expect(result).toContain('autocomplete')
    expect(result).toContain('command')
    expect(result).toContain('component: _Combobox')
  })

  test('handles item with empty arrays', () => {
    const item = {
      name: 'separator',
      type: 'registry:ui' as const,
      root_folder: 'components/ui',
      registryDependencies: [],
      files: [],
      categories: [],
    }

    const result = createComponentIndexEntry({ id: '_Separator', item })
    expect(result).toContain('registryDependencies: []')
    expect(result).toContain('categories: []')
  })

  test('handles item name with many hyphens', () => {
    const item = {
      name: 'my-very-long-component-name',
      type: 'registry:ui' as const,
      root_folder: 'components/ui',
    }

    const result = createComponentIndexEntry({ id: '_MyVeryLongComponentName', item })
    expect(result).toContain('"my-very-long-component-name"')
    expect(result).toContain('component: _MyVeryLongComponentName')
  })
})
