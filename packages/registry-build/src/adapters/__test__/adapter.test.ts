describe('createViteComponentImport', () => {
  test('uses React.lazy for dynamic import', () => {
    const result = createViteComponentImport({ componentPath: './button', id: '_Button' })
    expect(result).toContain('React.lazy')
    expect(result).toContain('import("./button")')
  })

  test('embeds the component identifier as variable name', () => {
    const result = createViteComponentImport({ componentPath: './x', id: '_Dialog' })
    expect(result).toContain('const _Dialog')
  })

  test('ends with a newline', () => {
    const result = createViteComponentImport({ componentPath: './x', id: '_A' })
    expect(result.endsWith('\n')).toBe(true)
  })

  test('does NOT include ssr option (vite has no ssr param)', () => {
    const result = createViteComponentImport({ componentPath: './x', id: '_A' })
    expect(result).not.toContain('ssr')
  })

  test('vite adapter ignores ssr option passed through getComponentIndexAdapter', () => {
    const adapter = getComponentIndexAdapter('vite')
    const withSsrTrue = adapter.renderImport({ componentPath: './x', id: '_A', ssr: true })
    const withSsrFalse = adapter.renderImport({ componentPath: './x', id: '_A', ssr: false })
    expect(withSsrTrue).toBe(withSsrFalse)
    expect(withSsrTrue).not.toContain('ssr')
  })
})

