describe('adapter isolation', () => {
  test('separate calls return distinct adapter objects', () => {
    const a = getComponentIndexAdapter('nextjs')
    const b = getComponentIndexAdapter('nextjs')
    expect(a).not.toBe(b)
    expect(a).toEqual(b)
  })

  test('mutating one adapter does not affect a new adapter', () => {
    const a = getComponentIndexAdapter('vite')
    ;(a as any).defaultHeader = 'MUTATED'
    const b = getComponentIndexAdapter('vite')
    expect(b.defaultHeader).toBe(VITE_COMPONENT_INDEX_HEADER)
  })
})

// ---------------------------------------------------------------------------
// Edge cases: empty / single / multiple component lists through renderImport
// ---------------------------------------------------------------------------

describe('adapter with varying component counts', () => {
  const frameworks = ['nextjs', 'vite', 'custom'] as const

  for (const fw of frameworks) {
    test(`${fw}: renderImport with empty componentPath`, () => {
      const adapter = getComponentIndexAdapter(fw)
      const result = adapter.renderImport({ componentPath: '', id: '_Empty', ssr: false })
      expect(typeof result).toBe('string')
    })
  }

  test('nextjs: multiple sequential renderImport calls produce independent results', () => {
    const adapter = getComponentIndexAdapter('nextjs')
    const a = adapter.renderImport({ componentPath: './button', id: '_Button', ssr: false })
    const b = adapter.renderImport({ componentPath: './dialog', id: '_Dialog', ssr: true })

    expect(a).toContain('_Button')
    expect(a).toContain('./button')
    expect(a).not.toContain('_Dialog')

    expect(b).toContain('_Dialog')
    expect(b).toContain('./dialog')
    expect(b).not.toContain('_Button')
  })

  test('vite: multiple sequential renderImport calls produce independent results', () => {
    const adapter = getComponentIndexAdapter('vite')
    const a = adapter.renderImport({ componentPath: './alert', id: '_Alert', ssr: false })
    const b = adapter.renderImport({ componentPath: './card', id: '_Card', ssr: false })

    expect(a).toContain('_Alert')
    expect(a).not.toContain('_Card')
    expect(b).toContain('_Card')
    expect(b).not.toContain('_Alert')
  })
})

