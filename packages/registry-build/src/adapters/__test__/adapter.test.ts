describe('createNextjsComponentImport', () => {
  test('embeds the component path in the import', () => {
    const result = createNextjsComponentImport({ componentPath: '@ui/button/button', id: '_Button', ssr: false })
    expect(result).toContain('@ui/button/button')
  })

  test('embeds the component identifier as variable name', () => {
    const result = createNextjsComponentImport({ componentPath: './x', id: '_MyComponent', ssr: false })
    expect(result).toContain('const _MyComponent')
  })

  test('ssr: false produces ssr: false in output', () => {
    const result = createNextjsComponentImport({ componentPath: './x', id: '_A', ssr: false })
    expect(result).toContain('ssr: false')
  })

  test('ssr: true produces ssr: true in output', () => {
    const result = createNextjsComponentImport({ componentPath: './x', id: '_A', ssr: true })
    expect(result).toContain('ssr: true')
  })

  test('ends with a newline', () => {
    const result = createNextjsComponentImport({ componentPath: './x', id: '_A', ssr: false })
    expect(result.endsWith('\n')).toBe(true)
  })

  test('handles paths with deep nesting', () => {
    const result = createNextjsComponentImport({
      componentPath: '@pkg/components/ui/forms/date-picker/date-picker',
      id: '_DatePicker',
      ssr: false,
    })
    expect(result).toContain('@pkg/components/ui/forms/date-picker/date-picker')
    expect(result).toContain('_DatePicker')
  })

  test('handles paths with special characters', () => {
    const result = createNextjsComponentImport({ componentPath: './@scope/my-lib', id: '_ScopedLib', ssr: false })
    expect(result).toContain('./@scope/my-lib')
  })
})

