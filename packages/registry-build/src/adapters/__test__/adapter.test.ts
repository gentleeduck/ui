describe('createComponentIndexEntry', () => {
  const minimalItem = {
    name: 'button',
    type: 'registry:ui' as const,
    root_folder: 'components/ui',
  }

  test('renders the component name as key', () => {
    const result = createComponentIndexEntry({ id: '_Button', item: minimalItem })
    expect(result).toContain('"button"')
  })

  test('renders the id as component reference', () => {
    const result = createComponentIndexEntry({ id: '_Button', item: minimalItem })
    expect(result).toContain('component: _Button')
  })

  test('renders type', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toContain('type: "registry:ui"')
  })

  test('renders root_folder', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toContain('root_folder: "components/ui"')
  })

  test('renders empty description when missing', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toContain('description: ""')
  })

  test('renders description when provided', () => {
    const result = createComponentIndexEntry({
      id: '_X',
      item: { ...minimalItem, description: 'A primary button' },
    })
    expect(result).toContain('description: "A primary button"')
  })

  test('renders empty source when missing', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toContain('source: ""')
  })

  test('renders source when provided', () => {
    const result = createComponentIndexEntry({
      id: '_X',
      item: { ...minimalItem, source: 'https://example.com' },
    })
    expect(result).toContain('source: "https://example.com"')
  })

  test('renders empty categories when missing', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toContain('categories: []')
  })

  test('renders categories when provided', () => {
    const result = createComponentIndexEntry({
      id: '_X',
      item: { ...minimalItem, categories: ['forms', 'inputs'] },
    })
    expect(result).toContain('categories: ["forms","inputs"]')
  })

  test('renders registryDependencies', () => {
    const result = createComponentIndexEntry({
      id: '_X',
      item: { ...minimalItem, registryDependencies: ['tooltip', 'popover'] },
    })
    expect(result).toContain('"tooltip"')
    expect(result).toContain('"popover"')
  })

  test('renders files array', () => {
    const result = createComponentIndexEntry({
      id: '_X',
      item: {
        ...minimalItem,
        files: [{ path: 'components/ui/button.tsx', type: 'registry:ui' }],
      },
    })
    expect(result).toContain('button.tsx')
    expect(result).toContain('registry:ui')
  })

  test('handles item with no files', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toBeDefined()
    expect(typeof result).toBe('string')
  })

  test('handles item with no registryDependencies', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result).toBeDefined()
  })

  test('handles item with multiple files', () => {
    const result = createComponentIndexEntry({
      id: '_DatePicker',
      item: {
        ...minimalItem,
        name: 'date-picker',
        files: [
          { path: 'components/ui/date-picker/date-picker.tsx', type: 'registry:ui' },
          { path: 'components/ui/date-picker/calendar.tsx', type: 'registry:ui' },
          { path: 'components/ui/date-picker/utils.ts', type: 'registry:ui' },
        ],
      },
    })
    expect(result).toContain('date-picker.tsx')
    expect(result).toContain('calendar.tsx')
    expect(result).toContain('utils.ts')
  })

  test('trailing comma at end of entry', () => {
    const result = createComponentIndexEntry({ id: '_X', item: minimalItem })
    expect(result.trimEnd().endsWith(',')).toBe(true)
  })
})

