describe('adapter shape contract', () => {
  const frameworks = ['nextjs', 'vite', 'custom'] as const

  for (const fw of frameworks) {
    test(`${fw} adapter has all required properties`, () => {
      const adapter = getComponentIndexAdapter(fw)

      expect(typeof adapter.defaultHeader).toBe('string')
      expect(typeof adapter.renderImport).toBe('function')
      expect(typeof adapter.renderEntry).toBe('function')
    })
  }

  test('all adapters share the same renderEntry implementation', () => {
    const nextjs = getComponentIndexAdapter('nextjs')
    const vite = getComponentIndexAdapter('vite')
    const custom = getComponentIndexAdapter('custom')

    expect(nextjs.renderEntry).toBe(vite.renderEntry)
    expect(vite.renderEntry).toBe(custom.renderEntry)
  })
})

